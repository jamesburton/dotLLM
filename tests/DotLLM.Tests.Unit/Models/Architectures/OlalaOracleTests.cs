/// <summary>
/// OVHcloud Olala (#1970): the CPU forward against the HF <c>modeling_olala.py</c> oracle. A tiny random model (every flag the 7A1B uses:
/// geodesic residual, Mamba-3 MIMO with data-dependent RoPE and trapezoid, differential TPA with token shift / scalable softmax / soft cap /
/// a window smaller than the sequence, latent MoE with expert bias, BF16 GGUF) is generated by <c>scripts/olala-oracle/olala_oracle.py tiny</c>
/// into <c>~/.dotllm/test-cache/olala-oracle</c> (override: <c>DOTLLM_OLALA_ORACLE_DIR</c>); tests skip when it is absent.
/// </summary>
/// <remarks>
/// The fixture is deliberately sensitive: logits are compared row by row (KL and max-abs), prefill and one-token decode separately (decode
/// is where the trapezoid carry, the token-shift carry and the scalable-softmax position live), and the greedy continuation must be identical.
/// Mutation record (what each deliberately wrong implementation does to these tests): docs/OLALA.md section 5.2.
/// </remarks>
public sealed class OlalaOracleTests
{
    private readonly ITestOutputHelper _output;

    public OlalaOracleTests(ITestOutputHelper output) => _output = output;

    internal sealed record Case(string Name, int Vocab, int[] Ids, int[] GreedyIds, float[] Full, float[] Greedy)
    {
        public int L => Ids.Length;
        public int N => GreedyIds.Length;
    }

    internal static string? OracleDir()
    {
        string? env = Environment.GetEnvironmentVariable("DOTLLM_OLALA_ORACLE_DIR");
        string dir = !string.IsNullOrEmpty(env) ? env
            : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".dotllm", "test-cache", "olala-oracle");
        return Directory.Exists(dir) ? dir : null;
    }

    internal static Case? LoadCase(string name)
    {
        string? dir = OracleDir();
        if (dir is null) return null;
        string meta = Path.Combine(dir, name + ".meta.json"), bin = Path.Combine(dir, name + ".logits.f32");
        if (!File.Exists(meta) || !File.Exists(bin)) return null;
        using var doc = JsonDocument.Parse(File.ReadAllText(meta));
        var r = doc.RootElement;
        int vocab = r.GetProperty("vocab").GetInt32();
        int[] ids = r.GetProperty("ids").EnumerateArray().Select(e => e.GetInt32()).ToArray();
        int[] gids = r.GetProperty("greedy_ids").EnumerateArray().Select(e => e.GetInt32()).ToArray();
        byte[] raw = File.ReadAllBytes(bin);
        var all = new float[raw.Length / 4];
        Buffer.BlockCopy(raw, 0, all, 0, raw.Length);
        Assert.Equal((long)(ids.Length + gids.Length) * vocab, all.Length);
        return new Case(name, vocab, ids, gids, all[..(ids.Length * vocab)], all[(ids.Length * vocab)..]);
    }

    private static unsafe float[] ToArray(ITensor t, int rows, int vocab)
    {
        var a = new float[rows * vocab];
        new ReadOnlySpan<float>((void*)t.DataPointer, a.Length).CopyTo(a);
        return a;
    }

    /// <summary>KL(ref || test) in nats from two logit rows.</summary>
    internal static double Kl(ReadOnlySpan<float> reference, ReadOnlySpan<float> test)
    {
        double mr = double.NegativeInfinity, mt = double.NegativeInfinity;
        for (int i = 0; i < reference.Length; i++) { mr = Math.Max(mr, reference[i]); mt = Math.Max(mt, test[i]); }
        double zr = 0, zt = 0;
        for (int i = 0; i < reference.Length; i++) { zr += Math.Exp(reference[i] - mr); zt += Math.Exp(test[i] - mt); }
        double lzr = Math.Log(zr) + mr, lzt = Math.Log(zt) + mt, kl = 0;
        for (int i = 0; i < reference.Length; i++)
        {
            double lp = reference[i] - lzr, lq = test[i] - lzt;
            kl += Math.Exp(lp) * (lp - lq);
        }
        return kl;
    }

    internal static int Argmax(ReadOnlySpan<float> row)
    {
        int best = 0;
        for (int i = 1; i < row.Length; i++) if (row[i] > row[best]) best = i;
        return best;
    }

    private static string? TinyGguf()
    {
        string? dir = OracleDir();
        string? p = dir is null ? null : Path.Combine(dir, "tiny.gguf");
        return p is not null && File.Exists(p) ? p : null;
    }

    private static OlalaTransformerModel Load(GgufFile gguf, out ModelConfig config)
    {
        config = GgufModelConfigExtractor.Extract(gguf.Metadata);
        return Assert.IsType<OlalaTransformerModel>(ModelLoader.CreateCpuModelFromGguf(gguf, config));
    }

    // "tiny*": HF with the query kept in F32 (the numerics dotLLM implements; only the BF16 K/V cast is shared) -> float-rounding agreement.
    // "tiny-hfbf16*": HF as shipped, which rounds the query and the attention output to bf16 -> ~1e-3 logit noise, same argmax.
    private static (double Kl, double MaxAbs) Tol(string name) => name.StartsWith("tiny-hfbf16", StringComparison.Ordinal) ? (1e-5, 8e-3) : (1e-9, 5e-5);

    [SkippableTheory]
    [InlineData("tiny")]
    [InlineData("tiny_short")]
    [InlineData("tiny-hfbf16")]
    [InlineData("tiny-hfbf16_short")]
    public void Prefill_AllRows_MatchHf(string name)
    {
        string? gguf = TinyGguf(); var c = LoadCase(name);
        Skip.If(gguf is null || c is null, "tiny Olala oracle not generated (scripts/olala-oracle/olala_oracle.py tiny)");
        using var file = GgufFile.Open(gguf!);
        using var model = Load(file, out _);
        int[] pos = Enumerable.Range(0, c!.L).ToArray();
        using var logits = model.Forward(c.Ids, pos, deviceId: -1);
        float[] got = ToArray(logits, c.L, c.Vocab);
        for (int t = 0; t < c.L; t++)
        {
            var refRow = c.Full.AsSpan(t * c.Vocab, c.Vocab); var gotRow = got.AsSpan(t * c.Vocab, c.Vocab);
            double kl = Kl(refRow, gotRow);
            double maxAbs = 0; for (int i = 0; i < c.Vocab; i++) maxAbs = Math.Max(maxAbs, Math.Abs(refRow[i] - gotRow[i]));
            _output.WriteLine($"{name} row {t}: KL {kl:E2}  max|dlogit| {maxAbs:E2}  argmax ref {Argmax(refRow)} got {Argmax(gotRow)}");
            var tol = Tol(name);
            Assert.True(kl < tol.Kl, $"{name} row {t}: KL {kl:E3}");
            Assert.True(maxAbs < tol.MaxAbs, $"{name} row {t}: max |dlogit| {maxAbs:E3}");
            Assert.Equal(Argmax(refRow), Argmax(gotRow));
        }
    }

    [SkippableTheory]
    [InlineData("tiny")]
    [InlineData("tiny_short")]
    [InlineData("tiny-hfbf16")]
    [InlineData("tiny-hfbf16_short")]
    public void DecodeSteps_TeacherForced_MatchHfCachePath(string name)
    {
        string? gguf = TinyGguf(); var c = LoadCase(name);
        Skip.If(gguf is null || c is null, "tiny Olala oracle not generated");
        using var file = GgufFile.Open(gguf!);
        using var model = Load(file, out _);
        // prefill, then one token at a time: exercises the trapezoid K/V carry, the token-shift carry, the angle state and the
        // scalable-softmax position that a single full forward never separates from the prompt.
        using (model.Forward(c!.Ids, Enumerable.Range(0, c.L).ToArray(), -1, null, lastTokenLogitsOnly: true)) { }
        model.ResetSequenceState();
        using var pre = model.Forward(c.Ids, Enumerable.Range(0, c.L).ToArray(), -1, null, lastTokenLogitsOnly: true);
        CheckRow(c, 0, ToArray(pre, 1, c.Vocab));
        for (int j = 1; j < c.N; j++)
        {
            using var step = model.Forward([c.GreedyIds[j - 1]], [c.L + j - 1], -1, null, lastTokenLogitsOnly: true);
            CheckRow(c, j, ToArray(step, 1, c.Vocab));
        }
    }

    private void CheckRow(Case c, int j, float[] got)
    {
        var refRow = c.Greedy.AsSpan(j * c.Vocab, c.Vocab);
        double kl = Kl(refRow, got);
        double maxAbs = 0; for (int i = 0; i < c.Vocab; i++) maxAbs = Math.Max(maxAbs, Math.Abs(refRow[i] - got[i]));
        _output.WriteLine($"{c.Name} step {j}: KL {kl:E2}  max|dlogit| {maxAbs:E2}");
        var tol = Tol(c.Name);
        Assert.True(kl < tol.Kl, $"{c.Name} step {j}: KL {kl:E3}");
        Assert.True(maxAbs < tol.MaxAbs, $"{c.Name} step {j}: max |dlogit| {maxAbs:E3}");
        Assert.Equal(Argmax(refRow), Argmax(got));
    }

    [SkippableTheory]
    [InlineData("tiny")]
    [InlineData("tiny-hfbf16")]
    public void GreedyContinuation_IsIdenticalToHf(string name)
    {
        string? gguf = TinyGguf(); var c = LoadCase(name);
        Skip.If(gguf is null || c is null, "tiny Olala oracle not generated");
        using var file = GgufFile.Open(gguf!);
        using var model = Load(file, out _);
        using var pre = model.Forward(c!.Ids, Enumerable.Range(0, c.L).ToArray(), -1, null, lastTokenLogitsOnly: true);
        var generated = new List<int> { Argmax(ToArray(pre, 1, c.Vocab)) };
        for (int j = 1; j < c.N; j++)
        {
            using var step = model.Forward([generated[^1]], [c.L + j - 1], -1, null, lastTokenLogitsOnly: true);
            generated.Add(Argmax(ToArray(step, 1, c.Vocab)));
        }
        Assert.Equal(c.GreedyIds, generated);
    }

    [SkippableFact]
    public void PositionZero_RestartsTheSequenceState()
    {
        string? gguf = TinyGguf(); var c = LoadCase("tiny");
        Skip.If(gguf is null || c is null, "tiny Olala oracle not generated");
        using var file = GgufFile.Open(gguf!);
        using var model = Load(file, out _);
        int[] pos = Enumerable.Range(0, c!.L).ToArray();
        using var a = model.Forward(c.Ids, pos, -1);
        using var b = model.Forward(c.Ids, pos, -1);     // a second call at position 0 must not see the first call's state
        Assert.Equal(ToArray(a, c.L, c.Vocab), ToArray(b, c.L, c.Vocab));
    }

    [SkippableFact]
    public void Config_ParsedFromGguf_CarriesTheOlalaContract()
    {
        string? gguf = TinyGguf();
        Skip.If(gguf is null, "tiny Olala oracle not generated");
        using var file = GgufFile.Open(gguf!);
        var cfg = GgufModelConfigExtractor.Extract(file.Metadata);
        Assert.Equal(Architecture.Olala, cfg.Architecture);
        var o = Assert.IsType<OlalaConfig>(cfg.Olala);
        Assert.Equal("MVMMV", o.LayerTypes);
        Assert.Equal(3, o.SsmLayerCount); Assert.Equal(2, o.AttentionLayerCount);
        Assert.Equal(2, o.NumNoiseHeads); Assert.Equal(6, o.NumSignalHeads);
        Assert.Equal(5, cfg.SlidingWindowSize);
        Assert.Null(cfg.PerLayerSlidingWindow);
        Assert.Equal(3f, cfg.AttnLogitSoftcap);
    }

    [Fact]
    public void RecurrentState_IsF32_ByArchitecturePolicy()
    {
        // #1971: the Mamba recurrent state is F32 (user sign-off 2026-11-25). The allocation must follow the policy: this fails the day someone
        // narrows any of the buffers without the #1971 evidence. It builds the state from the 7A1B geometry directly (no generated fixture),
        // so it runs in CI. Proven to fail (#1973 review) with the SSM matrix stored as packed bf16 (half the F32 elements); retyping a buffer
        // (NativeBuffer<Half>/<ushort>) changes the per-element byte checks below and every Span<float> call site.
        var o = new OlalaConfig
        {
            LayerTypes = "MMMMVMMMMVMMMMVMMMMVMMMMVMMMMVMMMMVM", SsmInner = 3072, StateSize = 128, GroupCount = 1, MambaHeadDim = 64, MimoRank = 4,
            NumRopeAngles = 32, NumSignalHeads = 36, NumNoiseHeads = 12, TpaRank = 4, GateBias = 1.15f, ExpertCount = 256, ExpertUsedCount = 6,
            ExpertFfLength = 768, SharedExpertFfLength = 1536, ExpertWeightsScale = 2.45f, MoeLatentSize = 384,
        };
        var cfg = new ModelConfig
        {
            Architecture = Architecture.Olala, VocabSize = 151936, HiddenSize = 1536, IntermediateSize = 0, NumLayers = 36,
            NumAttentionHeads = 48, NumKvHeads = 12, HeadDim = 128, MaxSequenceLength = 100000, Olala = o,
        };
        int f32 = OlalaStatePolicy.ElementBytes(OlalaStateStorage.F32);
        using var state = new OlalaSequenceState(o, cfg);
        Assert.Equal(29, state.Ssm.Length); Assert.Equal(7, state.Attn.Length);
        foreach (var s in state.Ssm)
        {
            Assert.Equal(OlalaStatePolicy.ElementBytes(OlalaStatePolicy.Ssm), (int)(s.Ssm.Bytes / s.Ssm.Count));
            Assert.Equal(OlalaStatePolicy.ElementBytes(OlalaStatePolicy.Angle), (int)(s.Angle.Bytes / s.Angle.Count));
            Assert.Equal(OlalaStatePolicy.ElementBytes(OlalaStatePolicy.Trapezoid), (int)(s.K.Bytes / s.K.Count));
            Assert.Equal(OlalaStatePolicy.ElementBytes(OlalaStatePolicy.Trapezoid), (int)(s.V.Bytes / s.V.Count));
        }
        foreach (var a in state.Attn)
        {
            Assert.Equal(OlalaStatePolicy.ElementBytes(OlalaStatePolicy.TokenShift), (int)(a.LastK.Bytes / a.LastK.Count));
            Assert.Equal(OlalaStatePolicy.ElementBytes(OlalaStatePolicy.TokenShift), (int)(a.LastV.Bytes / a.LastV.Count));
        }
        Assert.Equal(f32, state.SsmElementBytes);
        // docs/OLALA.md section 4: 1,572,864 + 6,144 + 98,304 + 12,288 bytes per M layer.
        Assert.Equal((1_572_864L + 6_144 + 98_304 + 12_288) * 29, state.RecurrentBytes);
    }
