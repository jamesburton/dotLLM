# Internal helpers
# ---------------------------------------------------------------------------

def _strip_tools_block(system_text: str) -> str:
    """Remove the embedded ``<tools>...</tools>`` block (and surrounding boilerplate)
    from a glaive_func_calling system message.

    The dataset injects the tool list inline; since we pass tools= to the template
    we must remove it to avoid duplication.  We strip:
    1. The literal ``<tools>\\n...\\n</tools>`` block.
    2. Any leading sentence fragment that introduced the block (the dataset's
       standard preamble ends with ``<tools>`` so this is typically the same line).
    After stripping, a bare preamble like
       "You are a function calling AI model. You are provided with function
       signatures within <tools></tools> XML tags."
    is collapsed to a plain
       "You are a helpful assistant."
    when nothing meaningful remains — but if the author added a non-boilerplate
    prefix we preserve that instead.
    """
    import re

    # Remove the <tools>...</tools> block (including tags and surrounding newlines)
    stripped = re.sub(r"<tools>\s*.*?\s*</tools>", "", system_text, flags=re.DOTALL)

    # Remove the standard glaive boilerplate sentence that references <tools> tags
    stripped = re.sub(
        r"You are provided with function signatures within <tools></tools> XML tags\.?\s*",
        "",
        stripped,
    )
    # Remove inline tool-call format instructions that are re-generated by the template
    stripped = re.sub(
        r"Use the following pydantic model json schema.*?</tool_call>",
        "",
        stripped,
        flags=re.DOTALL,
    )
    stripped = re.sub(
        r"For each function call return a json object.*?</tool_call>",
        "",
        stripped,
        flags=re.DOTALL,
    )
    stripped = stripped.strip()
    if not stripped:
        stripped = "You are a helpful assistant."
    return stripped
