using DotLLM.Cuda.Interop;
using DotLLM.Models.Adapters.Ternary;

namespace DotLLM.Cuda;

/// <summary>
/// Device-resident ternary residual adapters for the CUDA backend (#1618): the CUDA counterpart of
/// <c>VulkanTernaryResidualModifier</c>, launching <c>native/kernels/ternary_adapter_residual_f32.cu</c> in place on the F32
/// device residual. Uses the same packed bytes as Vulkan (<see cref="TernaryDevicePack"/>: 2-bit plus/minus bitmasks, never expanded).
/// </summary>
/// <remarks>
/// <b>Status: build-verified only.</b> It has not run on an NVIDIA GPU (the Strix dev box has none; the T5500 is off limits
/// without the user's go-ahead) and it is not wired into <c>CudaTransformerModel</c> yet. The <c>.ptx</c> is generated by
/// <c>native/build_ptx.bat</c> / the csproj nvcc step and is not checked in. <see cref="TryLoad"/> returns null when the PTX is absent.
/// </remarks>
public sealed unsafe class CudaTernaryResidualModifier : IDisposable
{
    /// <summary>Largest summed rank per layer (shared strips are 256 wide).</summary>
    public const int MaxRank = 256;
    /// <summary>Largest supported residual width (shared int8 row).</summary>
    public const int MaxHiddenSize = 8192;
    private const int Threads = 256;

    private sealed class Layer
    {
        public nint Masks, Scales, Meta;
        public int Circuits, TotalRank, UpScaleBase, UpScaleStride;
    }

    private readonly CudaModule _module;
    private readonly nint _func;
    private readonly Dictionary<int, Layer> _layers = new();
    private readonly int _d;
    private readonly TernaryScaleStorage _storage;
    private bool _disposed;

    private CudaTernaryResidualModifier(CudaModule module, nint func, int d, TernaryScaleStorage storage)
    {
        _module = module; _func = func; _d = d; _storage = storage;
    }

    /// <summary>Residual width.</summary>
    public int DModel => _d;

    /// <summary>Whether this modifier acts after <paramref name="layer"/>.</summary>
    public bool AppliesTo(int layer) => _layers.ContainsKey(layer);

    /// <summary>
    /// Loads <c>ternary_adapter_residual_f32.ptx</c> from <paramref name="ptxDir"/> and uploads the packages (grouped by
    /// <c>TargetLayer</c>, registration order). Returns null when the PTX has not been generated. A CUDA context must be current.
    /// </summary>
    public static CudaTernaryResidualModifier? TryLoad(string ptxDir, IReadOnlyList<NsAdapterPackage> packages,
        TernaryScaleStorage storage = TernaryScaleStorage.F32)
    {
        ArgumentNullException.ThrowIfNull(packages);
        if (packages.Count == 0) throw new ArgumentException("no adapter packages given", nameof(packages));
        string ptx = Path.Combine(ptxDir, "ternary_adapter_residual_f32.ptx");
        if (!File.Exists(ptx)) return null;
        int d = packages[0].Manifest.InputDimension;
        if (d <= 0 || d > MaxHiddenSize) throw new NotSupportedException($"ternary adapter D={d} exceeds the CUDA kernel limit {MaxHiddenSize}");
        foreach (var p in packages)
        {
            p.ValidateDimensions();
            if (p.Manifest.InputDimension != d) throw new InvalidOperationException($"adapter '{p.Manifest.Domain}' has D={p.Manifest.InputDimension}, expected D={d}");
        }

        var module = CudaModule.LoadFromFile(ptx);
        nint func = module.GetFunction(storage == TernaryScaleStorage.F16 ? "ternary_adapter_residual_f32_f16scales" : "ternary_adapter_residual_f32");
        var self = new CudaTernaryResidualModifier(module, func, d, storage);
        try
        {
            foreach (var g in packages.GroupBy(p => p.Manifest.TargetLayer).OrderBy(g => g.Key))
            {
                var list = g.ToList();
                if (list.Sum(p => p.Manifest.Rank) > MaxRank)
                    throw new NotSupportedException($"summed ternary rank at layer {g.Key} exceeds {MaxRank}");
                var pk = TernaryDevicePack.Build(list, d, storage);
                var layer = new Layer { Circuits = pk.Circuits, TotalRank = pk.TotalRank, UpScaleBase = pk.UpScaleBase, UpScaleStride = pk.UpScaleStride };
                self._layers[g.Key] = layer;   // registered first so Dispose frees partial uploads
                layer.Masks = Upload(pk.Masks); layer.Scales = Upload(pk.Scales); layer.Meta = Upload(pk.Meta);
            }
        }
        catch { self.Dispose(); throw; }
        return self;
    }

    private static nint Upload(byte[] bytes)
    {
        CudaDriverApi.cuMemAlloc_v2(out nint dev, (nuint)Math.Max(bytes.Length, 16)).ThrowOnError();
        fixed (byte* p = bytes)
            CudaDriverApi.cuMemcpyHtoD_v2(dev, (nint)p, (nuint)bytes.Length).ThrowOnError();
        return dev;
    }

    /// <summary>
    /// Applies the adapters after <paramref name="layer"/> in place on <paramref name="residualF32Dev"/>
    /// (<c>[tokenCount x D]</c> F32 device memory), asynchronously on <paramref name="stream"/>.
    /// </summary>
    public void Apply(nint residualF32Dev, int layer, int tokenCount, nint stream)
    {
        if (!_layers.TryGetValue(layer, out var l)) return;
        nint h = residualF32Dev, masks = l.Masks, scales = l.Scales, meta = l.Meta;
        int d = _d, n = tokenCount, nc = l.Circuits, tr = l.TotalRank, wpr64 = TernaryDevicePack.WordsPerRow(_d) / 2;
        int ub = l.UpScaleBase, us = l.UpScaleStride;
        void** args = stackalloc void*[] { &h, &masks, &scales, &meta, &d, &n, &nc, &tr, &wpr64, &ub, &us };
        CudaDriverApi.cuLaunchKernel(_func, (uint)tokenCount, 1, 1, Threads, 1, 1, 0, stream, (nint)args, 0).ThrowOnError();
    }

    /// <inheritdoc/>
    public void Dispose()
    {
        if (_disposed) return;
        _disposed = true;
        foreach (var l in _layers.Values)
        {
            if (l.Masks != 0) CudaDriverApi.cuMemFree_v2(l.Masks);
            if (l.Scales != 0) CudaDriverApi.cuMemFree_v2(l.Scales);
            if (l.Meta != 0) CudaDriverApi.cuMemFree_v2(l.Meta);
        }
        _layers.Clear();
        _module.Dispose();
    }
}
