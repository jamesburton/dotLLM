using System.Text.RegularExpressions;
using DotLLM.Tokenizers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DotLLM.ChunkReuse.CodeCorpus;

/// <summary>
/// Symbol-level chunks from the Roslyn syntax tree: every method, property, constructor, operator, event, indexer, enum,
/// delegate and type starts its own chunk, so a chunk holds one member (with its leading comments, attributes and blank
/// lines, which Roslyn attaches to it as trivia). Chunks are whole lines, cover the file without overlap and are tokenised
/// once each; no chunk exceeds <see cref="MaxChunkTokens"/> (default 512, the E1/E2 chunk size).
/// </summary>
/// <remarks>
/// Rules, in order:
/// <list type="number">
/// <item>Split points are the line starts of each member's full span (trivia included). Namespaces and types with members are
/// containers: their header (usings, <c>namespace</c> line, type declaration and opening brace) carries no member, so it
/// glues forward to the next chunk; a type's closing brace stays with its last member.</item>
/// <item>Consecutive field/event-field declarations form one chunk, and so do consecutive top-level statements (a local
/// function among them included).</item>
/// <item>A member starting mid-line after other code (e.g. several members on one line) does not split.</item>
/// <item>A chunk over the limit is re-split greedily at the line starts of its inner statements and members (blocks belong to
/// their statement), then at line starts, and a single line over the limit is cut into token slices of the limit (those
/// pieces share a line, and are not <see cref="Chunk.WireEligible"/>).</item>
/// </list>
/// Partial types need nothing special (each part is chunked in its own file); nested types are containers like any type;
/// a file with parse errors is chunked from whatever members Roslyn recovered (coverage still holds); generated code is
/// chunked normally — <see cref="IsGenerated"/> lets the corpus loader exclude it.
/// </remarks>
public sealed partial class SymbolChunker : IChunker
{
    /// <summary>Parse options for corpus code: the newest language version, no preprocessor symbols.</summary>
    public static readonly CSharpParseOptions ParseOptions = new(LanguageVersion.Preview, DocumentationMode.Parse);

    private readonly ITokenizer _tokenizer;

    /// <summary>Creates the chunker.</summary>
    /// <param name="tokenizer">The model's tokenizer (each chunk's text is encoded with <see cref="ChunkTokenization.Encode"/>).</param>
    /// <param name="maxChunkTokens">Largest chunk in tokens (default 512).</param>
    public SymbolChunker(ITokenizer tokenizer, int maxChunkTokens = 512)
    {
        ArgumentNullException.ThrowIfNull(tokenizer);
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(maxChunkTokens);
        _tokenizer = tokenizer;
        MaxChunkTokens = maxChunkTokens;
    }

    /// <inheritdoc />
    public string Name => $"symbol-{MaxChunkTokens}";

    /// <inheritdoc />
    public int MaxChunkTokens { get; }

    /// <summary>
    /// True for generated code: a <c>.g.cs</c>, <c>.g.i.cs</c>, <c>.designer.cs</c> or <c>.generated.cs</c> file name, an
    /// <c>&lt;auto-generated</c> marker near the top, or a <c>[GeneratedCode(...)]</c> attribute.
    /// </summary>
    public static bool IsGenerated(SourceFile file)
    {
        ArgumentNullException.ThrowIfNull(file);
        string name = file.Path.ToLowerInvariant();
        if (name.EndsWith(".g.cs", StringComparison.Ordinal) || name.EndsWith(".g.i.cs", StringComparison.Ordinal)
            || name.EndsWith(".designer.cs", StringComparison.Ordinal) || name.EndsWith(".generated.cs", StringComparison.Ordinal))
            return true;
        if (file.Text.AsSpan(0, Math.Min(file.Text.Length, 4000)).Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            return true;
        return GeneratedCodeAttribute().IsMatch(file.Text);
    }

    [GeneratedRegex(@"\[\s*(global::)?(System\.CodeDom\.Compiler\.)?GeneratedCode(Attribute)?\s*\(")]
    private static partial Regex GeneratedCodeAttribute();

    /// <inheritdoc />
    public IReadOnlyList<Chunk> Chunk(SourceFile file)
    {
        ArgumentNullException.ThrowIfNull(file);
        string text = file.Text;
        if (text.Length == 0) return [];
        CompilationUnitSyntax root = CSharpSyntaxTree.ParseText(text, ParseOptions, file.Path).GetCompilationUnitRoot();
        return new Splitter(this, file.Path, text, root).Run();
    }

    private sealed class Splitter(SymbolChunker owner, string path, string text, CompilationUnitSyntax root)
    {
        private readonly LineIndex _lines = new(text);
        private readonly List<int> _marks = [];
        private readonly List<int> _leaves = [];
        private readonly List<Chunk> _out = [];
        private int Limit => owner.MaxChunkTokens;

        public List<Chunk> Run()
        {
            VisitMembers(root.Members);

            var bounds = _marks.Where(p => p > 0 && p < text.Length).Append(0).Append(text.Length).Distinct().Order().ToArray();
            _leaves.Sort();
            // Glue header-only pieces (no member starts in them) forward; a trailing header-only piece glues backward.
            var pieces = new List<(int Start, int End)>();
            int pending = 0;
            for (int i = 0; i + 1 < bounds.Length; i++)
            {
                int s = bounds[i], e = bounds[i + 1];
                if (!HasLeaf(s, e)) continue;
                pieces.Add((pending, e));
                pending = e;
            }
            if (pieces.Count == 0) pieces.Add((0, text.Length));
            else if (pending < text.Length) pieces[^1] = (pieces[^1].Start, text.Length);

            foreach ((int s, int e) in pieces) Emit(s, e);
            return _out;
        }

        private bool HasLeaf(int start, int end)
        {
            int i = _leaves.BinarySearch(start);
            if (i < 0) i = ~i;
            return i < _leaves.Count && _leaves[i] < end;
        }

        private void VisitMembers(SyntaxList<MemberDeclarationSyntax> members)
        {
            MemberDeclarationSyntax? prev = null;
            foreach (MemberDeclarationSyntax m in members)
            {
                switch (m)
                {
                    case BaseNamespaceDeclarationSyntax ns:
                        Mark(m);
                        VisitMembers(ns.Members);
                        break;
                    case TypeDeclarationSyntax t when t.Members.Count > 0:
                        Mark(m);
                        VisitMembers(t.Members);
                        break;
                    case GlobalStatementSyntax:
                        if (prev is not GlobalStatementSyntax) Mark(m);
                        _leaves.Add(m.SpanStart);
                        break;
                    case BaseFieldDeclarationSyntax:
                        if (prev is not BaseFieldDeclarationSyntax) Mark(m);
                        _leaves.Add(m.SpanStart);
                        break;
                    default: // methods, ctors, properties, events, indexers, operators, enums, delegates, empty types, incomplete members
                        Mark(m);
                        _leaves.Add(m.SpanStart);
                        break;
                }
                prev = m;
            }
        }

        private void Mark(SyntaxNode node)
        {
            int aligned = AlignedStart(node.FullSpan.Start);
            if (aligned >= 0) _marks.Add(aligned);
        }

        /// <summary>The line start of <paramref name="pos"/> when only whitespace precedes it on its line, else -1.</summary>
        private int AlignedStart(int pos)
        {
            if (pos >= text.Length) return -1;
            int lineStart = _lines.LineStartOf(pos);
            for (int i = lineStart; i < pos; i++)
                if (!char.IsWhiteSpace(text[i])) return -1;
            return lineStart;
        }

        private void Add(int start, int end, int[] ids, bool wireEligible = true)
        {
            int startLine = _lines.LineOf(start);
            int endLine = end > start ? _lines.LineOf(end - 1) : startLine; // a zero-length piece (see SliceTokens) has one line
            _out.Add(new Chunk(path, startLine, endLine, ids) { StartOffset = start, EndOffset = end, WireEligible = wireEligible });
        }

        private void Emit(int start, int end)
        {
            int[] ids = ChunkTokenization.Encode(owner._tokenizer, text[start..end]);
            if (ids.Length <= Limit)
            {
                Add(start, end, ids);
                return;
            }
            // Inner statement / member starts inside the piece, aligned to line starts.
            var cuts = root.DescendantNodes(n => n.FullSpan.IntersectsWith(new Microsoft.CodeAnalysis.Text.TextSpan(start, end - start)))
                .Where(n => n is (StatementSyntax and not BlockSyntax) or MemberDeclarationSyntax or SwitchSectionSyntax
                            or AccessorDeclarationSyntax or ElseClauseSyntax or CatchClauseSyntax or FinallyClauseSyntax)
                .Select(n => AlignedStart(n.FullSpan.Start))
                .Where(p => p > start && p < end);
            Pack(start, end, cuts, PackLines);
        }

        private void PackLines(int start, int end) => Pack(start, end, _lines.LineStartsInside(start, end), SliceTokens);

        /// <summary>Greedy: from the current point, take the furthest cut whose text fits the limit; an uncut segment over the
        /// limit goes to <paramref name="tooBig"/>.</summary>
        private void Pack(int start, int end, IEnumerable<int> cutPositions, Action<int, int> tooBig)
        {
            int[] points = cutPositions.Append(end).Distinct().Order().ToArray();
            int cur = start, j = 0;
            while (cur < end)
            {
                int best = -1;
                int[]? bestIds = null;
                for (int k = j; k < points.Length; k++)
                {
                    int[] ids = ChunkTokenization.Encode(owner._tokenizer, text[cur..points[k]]);
                    if (ids.Length > Limit) break;
                    best = k;
                    bestIds = ids;
                }
                if (best < 0)
                {
                    tooBig(cur, points[j]);
                    cur = points[j];
                    j++;
                }
                else
                {
                    Add(cur, points[best], bestIds!);
                    cur = points[best];
                    j = best + 1;
                }
            }
        }

        /// <summary>One line over the limit: slices of <see cref="Limit"/> token ids; offsets from the decoded slice lengths.</summary>
        /// <remarks>
        /// Caveat: the char offsets (and so <see cref="Chunk.StartOffset"/>/<see cref="Chunk.EndOffset"/> of the pieces) come from
        /// decoding the ids up to each boundary. With a byte-level BPE, a boundary inside a multi-byte UTF-8 character decodes to
        /// replacement characters, so a boundary offset can be off by that character (the token ids are unaffected). Offsets are
        /// clamped to stay within the line and never go back, so the pieces always tile the line exactly; a piece can then be
        /// zero-length. Only over-long single lines take this path.
        /// </remarks>
        private void SliceTokens(int start, int end)
        {
            int[] ids = ChunkTokenization.Encode(owner._tokenizer, text[start..end]);
            int offset = start;
            for (int s = 0; s < ids.Length; s += Limit)
            {
                int stop = Math.Min(s + Limit, ids.Length);
                int[] slice = ids.AsSpan(s, stop - s).ToArray();
                // Decode the whole prefix (not this slice alone), so replacement characters do not accumulate across slices.
                int next = stop >= ids.Length ? end
                    : Math.Clamp(start + owner._tokenizer.Decode(ids.AsSpan(0, stop)).Length, offset, end);
                Add(offset, next, slice, wireEligible: false); // a token slice: its text need not tokenise to its ids
                offset = next;
            }
        }
    }
}
