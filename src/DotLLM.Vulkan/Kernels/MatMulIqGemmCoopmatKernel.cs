using DotLLM.Core.Configuration;
using DotLLM.Vulkan.Interop;

namespace DotLLM.Vulkan.Kernels;

/// <summary>
/// Native dense IQ1_S / IQ2_XS / IQ2_S / IQ3_XXS / IQ3_S batched GEMM on the shared 128x128, BK=32, four-wave64-subgroup
/// cooperative-matrix tile (issue #1677): <c>C[N, M] = B[N, K] @ W_iq[M, K]ᵀ</c>. Each workgroup decodes its IQ sub-blocks (codebook
/// grids, ksigns) straight into the F16 shared-memory operand, so the dense prefill no longer dequantises the weight into the F16
/// scratch of <see cref="IqF16PrefillMatmul"/> (#621 / #1060, PRECISION.md VX4). One class serves every <see cref="Quant"/>; the
/// shaders are generated by <c>native/vulkan/gen_iq_gemm_coopmat.py</c> from the IQ2_XXS wrapper (<see cref="MatMulIq2XxsGemmCoopmatKernel"/>).
/// </summary>
/// <remarks>
/// <para><b>Numerics.</b> The staged operand is computed exactly as the matching <c>iq*_dequant_f16.comp</c> computes it, so the result
/// equals the F16 scratch path up to F32 accumulation order.</para>
/// <para><b>wave64 ONLY, and that is a correctness gate</b> (as for every shader on the blocked template, see
/// <see cref="MatMulQ4_0GemmCoopmatKernel"/>). Check <see cref="IsSupportedOn"/> before <see cref="Create"/>.</para>
/// </remarks>
public sealed class MatMulIqGemmCoopmatKernel : IDisposable
{
    /// <summary>Environment variable that disables these kernels so callers fall back to the F16 scratch / scalar IQ GEMMs (A/B).</summary>
    public const string DisableEnvVar = "DOTLLM_VULKAN_DISABLE_IQ_COOPMAT";

    /// <summary>Elements per IQ super-block; <c>k</c> must be a multiple of it.</summary>
    public const int GroupSize = 256;

    /// <summary>The formats this kernel exists for.</summary>
    public static readonly QuantizationType[] Formats =
    {
        QuantizationType.IQ1_S, QuantizationType.IQ2_XS, QuantizationType.IQ2_S, QuantizationType.IQ3_XXS, QuantizationType.IQ3_S,
    };

    private const int Tile = 128;
    private const int FixedBindings = 3;                    // W, B, C (+ codebooks)
    private const int PushConstantBytes = 4 * sizeof(uint); // M, K, N, blocksPerRow

    private readonly VulkanDevice _device;
    private readonly VulkanModule _module;
    private readonly ComputePipeline _pipeline;
    private readonly nint _descriptorPool;
    private readonly DescriptorSetCache _descriptorCache;
    private readonly VulkanDevice.Buffer[] _codebooks;
    private readonly IDisposable? _ownedCodebooks;
    private bool _disposed;

    /// <summary>Dispatches recorded by every instance, read by tests to prove the native path ran.</summary>
    internal static long Dispatches;

    /// <summary>The weight format this instance decodes.</summary>
    public QuantizationType Quant { get; }

    /// <summary>Bytes per 256-element super-block of <see cref="Quant"/>.</summary>
    public int BlockBytes { get; }

    private MatMulIqGemmCoopmatKernel(QuantizationType quant, VulkanDevice device, VulkanModule module, ComputePipeline pipeline, nint pool,
        VulkanDevice.Buffer[] codebooks, IDisposable? ownedCodebooks)
    {
        Quant = quant;
        BlockBytes = BlockBytesOf(quant);
        _device = device;
        _module = module;
        _pipeline = pipeline;
        _descriptorPool = pool;
        _codebooks = codebooks;
        _ownedCodebooks = ownedCodebooks;
        _descriptorCache = new DescriptorSetCache(device, pool, pipeline, buffersPerSet: FixedBindings + codebooks.Length);
    }

    /// <summary>True when a shader exists for <paramref name="quant"/>.</summary>
    public static bool Handles(QuantizationType quant) => quant is QuantizationType.IQ1_S or QuantizationType.IQ2_XS
        or QuantizationType.IQ2_S or QuantizationType.IQ3_XXS or QuantizationType.IQ3_S;

    /// <summary>Super-block bytes of <paramref name="quant"/> (50 / 74 / 82 / 98 / 110).</summary>
    public static int BlockBytesOf(QuantizationType quant) => quant switch
    {
        QuantizationType.IQ1_S => 50,
        QuantizationType.IQ2_XS => 74,
        QuantizationType.IQ2_S => 82,
        QuantizationType.IQ3_XXS => 98,
        QuantizationType.IQ3_S => 110,
        _ => throw new ArgumentOutOfRangeException(nameof(quant), quant, "no dense IQ coopmat GEMM for this format"),
    };

    /// <summary>SPIR-V file name of the shader for <paramref name="quant"/>.</summary>
    public static string SpvFileName(QuantizationType quant) => quant switch
    {
        QuantizationType.IQ1_S => "matmul_iq1_s_gemm_coopmat_128x128x4.spv",
        QuantizationType.IQ2_XS => "matmul_iq2_xs_gemm_coopmat_128x128x4.spv",
        QuantizationType.IQ2_S => "matmul_iq2_s_gemm_coopmat_128x128x4.spv",
        QuantizationType.IQ3_XXS => "matmul_iq3_xxs_gemm_coopmat_128x128x4.spv",
        QuantizationType.IQ3_S => "matmul_iq3_s_gemm_coopmat_128x128x4.spv",
        _ => throw new ArgumentOutOfRangeException(nameof(quant), quant, "no dense IQ coopmat GEMM for this format"),
    };

    /// <summary>
    /// Whether the kernel for <paramref name="quant"/> can run on <paramref name="device"/>: cooperative matrix present, native wave64,
    /// the SPIR-V compiled, and not disabled by <see cref="DisableEnvVar"/>.
    /// </summary>
    /// <param name="device">The Vulkan device.</param>
    /// <param name="spvDir">Directory holding the compiled shaders.</param>
    /// <param name="quant">The weight format.</param>
    /// <returns>True when <see cref="Create"/> may be called.</returns>
    public static bool IsSupportedOn(VulkanDevice device, string spvDir, QuantizationType quant)
        => Handles(quant)
           && Environment.GetEnvironmentVariable(DisableEnvVar) != "1"
           && device.HasCooperativeMatrix
           && device.SubgroupSize == 64
           && File.Exists(Path.Combine(spvDir, SpvFileName(quant)));

    /// <summary>
    /// Creates the kernel for <paramref name="quant"/> on the caller's codebooks when <see cref="IsSupportedOn"/> holds, otherwise null.
    /// </summary>
    /// <param name="device">The Vulkan device.</param>
    /// <param name="spvDir">Directory holding the compiled shaders.</param>
    /// <param name="quant">The weight format.</param>
    /// <param name="iq2">IQ2 grids + ksigns (IQ2_XS, IQ2_S); owned by the caller and outliving the kernel.</param>
    /// <param name="iq3">IQ3 grids + ksigns (IQ3_XXS, IQ3_S); owned by the caller and outliving the kernel.</param>
    /// <param name="iq1">IQ1_S grid; owned by the caller and outliving the kernel.</param>
    /// <returns>The kernel, or null on an unsupported device.</returns>
    internal static MatMulIqGemmCoopmatKernel? TryCreate(VulkanDevice device, string spvDir, QuantizationType quant,
        Iq2Codebooks? iq2 = null, Iq3Codebooks? iq3 = null, Iq1Codebooks? iq1 = null)
        => IsSupportedOn(device, spvDir, quant) ? CreateCore(device, spvDir, quant, iq2, iq3, iq1) : null;

    /// <summary>Loads the SPIR-V for <paramref name="quant"/>, uploads its own codebooks and creates the pipeline. Check <see cref="IsSupportedOn"/> first.</summary>
    /// <param name="device">The Vulkan device.</param>
    /// <param name="spvDir">Directory holding the compiled shaders.</param>
    /// <param name="quant">The weight format.</param>
    /// <returns>The kernel.</returns>
    /// <exception cref="FileNotFoundException">The SPIR-V is missing.</exception>
    public static MatMulIqGemmCoopmatKernel Create(VulkanDevice device, string spvDir, QuantizationType quant)
        => CreateCore(device, spvDir, quant, null, null, null);

    private static MatMulIqGemmCoopmatKernel CreateCore(VulkanDevice device, string spvDir, QuantizationType quant,
        Iq2Codebooks? iq2, Iq3Codebooks? iq3, Iq1Codebooks? iq1)
    {
        string path = Path.Combine(spvDir, SpvFileName(quant));
        if (!File.Exists(path))
            throw new FileNotFoundException(
                $"Vulkan SPIR-V not found: {path}. Run native/vulkan/build.sh (or build.ps1) after installing the Vulkan SDK.");

        // Codebooks the caller did not supply are uploaded here and owned by the kernel.
        IDisposable? owned = null;
        VulkanDevice.Buffer[] codebooks;
        switch (quant)
        {
            case QuantizationType.IQ1_S:
                if (iq1 is null) { var c = Iq1Codebooks.Create(device); owned = c; iq1 = c; }
                codebooks = new[] { iq1.Iq1SGrid };
                break;
            case QuantizationType.IQ2_XS:
                if (iq2 is null) { var c = Iq2Codebooks.Create(device); owned = c; iq2 = c; }
                codebooks = new[] { iq2.Iq2XsGrid, iq2.Ksigns };
                break;
            case QuantizationType.IQ2_S:
                if (iq2 is null) { var c = Iq2Codebooks.Create(device); owned = c; iq2 = c; }
                codebooks = new[] { iq2.Iq2SGrid };
                break;
            case QuantizationType.IQ3_XXS:
                if (iq3 is null) { var c = Iq3Codebooks.Create(device); owned = c; iq3 = c; }
                codebooks = new[] { iq3.Iq3XxsGrid, iq3.Ksigns };
                break;
            case QuantizationType.IQ3_S:
                if (iq3 is null) { var c = Iq3Codebooks.Create(device); owned = c; iq3 = c; }
                codebooks = new[] { iq3.Iq3SGrid };
                break;
            default:
                throw new ArgumentOutOfRangeException(nameof(quant), quant, "no dense IQ coopmat GEMM for this format");
        }

        try
        {
            int bindingCount = FixedBindings + codebooks.Length;
            var module = VulkanModule.LoadFromFile(device, path);
            ComputePipeline pipeline;
            try
            {
                Span<VkDescriptorBinding> bindings = stackalloc VkDescriptorBinding[bindingCount];
                for (int i = 0; i < bindingCount; i++) bindings[i] = new VkDescriptorBinding((uint)i);
                pipeline = module.CreateComputePipeline(
                    entryPoint: "main", bindings: bindings, pushConstantBytes: PushConstantBytes, requiredSubgroupSize: 0);
            }
            catch
            {
                module.Dispose();
                throw;
            }

            nint pool = KernelSupport.CreateDescriptorPool(device, buffersPerSet: (uint)bindingCount);
            return new MatMulIqGemmCoopmatKernel(quant, device, module, pipeline, pool, codebooks, owned);
        }
        catch
        {
            owned?.Dispose();
            throw;
        }
    }

    /// <summary>Drops every cached descriptor set; call when scratch buffers have been re-allocated.</summary>
    internal void InvalidateDescriptorCache() => _descriptorCache.Reset();

    /// <summary>Dispatches synchronously (one-shot submit + fence wait); production uses <see cref="Record"/>.</summary>
    /// <param name="weights">Packed <see cref="Quant"/> weights, <paramref name="m"/> rows of <c>k / 256</c> super-blocks.</param>
    /// <param name="input">FP32 input <c>[n, k]</c>.</param>
    /// <param name="output">FP32 output <c>[n, m]</c>.</param>
    /// <param name="m">Output rows.</param>
    /// <param name="k">Contraction length; a multiple of 256.</param>
    /// <param name="n">Token rows.</param>
    public void Launch(VulkanDevice.Buffer weights, VulkanDevice.Buffer input, VulkanDevice.Buffer output, int m, int k, int n)
    {
        using var ctx = _device.CreateSubmitContext();
        ctx.Begin();
        Record(ctx.CommandBuffer, weights, input, output, m, k, n);
        ctx.SubmitAndWait();
    }

    /// <summary>Records the GEMM into <paramref name="cmdBuf"/> without submitting.</summary>
    /// <param name="cmdBuf">Open command buffer.</param>
    /// <param name="weights">Packed <see cref="Quant"/> weights, <paramref name="m"/> rows of <c>k / 256</c> super-blocks.</param>
    /// <param name="input">FP32 input <c>[n, k]</c>.</param>
    /// <param name="output">FP32 output <c>[n, m]</c>.</param>
    /// <param name="m">Output rows.</param>
    /// <param name="k">Contraction length; a multiple of 256.</param>
    /// <param name="n">Token rows.</param>
    /// <exception cref="ArgumentException">A dimension or buffer size is invalid.</exception>
    public unsafe void Record(nint cmdBuf,
        VulkanDevice.Buffer weights, VulkanDevice.Buffer input, VulkanDevice.Buffer output, int m, int k, int n)
    {
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(m);
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(k);
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(n);
        if (k % GroupSize != 0)
            throw new ArgumentException($"k must be a multiple of {GroupSize}, got {k}", nameof(k));

        int blocksPerRow = k / GroupSize;
        long weightsMin = (long)m * blocksPerRow * BlockBytes;
        if (weights.Size < weightsMin)
            throw new ArgumentException($"Weights buffer too small: need >= {weightsMin} bytes, got {weights.Size}.", nameof(weights));
        if (input.Size < (long)n * k * sizeof(float)) throw new ArgumentException("Input buffer too small.", nameof(input));
        if (output.Size < (long)n * m * sizeof(float)) throw new ArgumentException("Output buffer too small.", nameof(output));

        Span<nint> buffers = stackalloc nint[FixedBindings + _codebooks.Length];
        buffers[0] = weights.Handle;
        buffers[1] = input.Handle;
        buffers[2] = output.Handle;
        for (int i = 0; i < _codebooks.Length; i++) buffers[FixedBindings + i] = _codebooks[i].Handle;
        nint descriptorSet = _descriptorCache.GetOrCreate(buffers);

        VulkanApi.vkCmdBindPipeline(cmdBuf, VkPipelineBindPoint.Compute, _pipeline.Pipeline);
        VulkanApi.vkCmdBindDescriptorSets(cmdBuf, VkPipelineBindPoint.Compute, _pipeline.Layout, 0, 1, descriptorSet, 0, 0);

        Span<uint> pc = stackalloc uint[4] { (uint)m, (uint)k, (uint)n, (uint)blocksPerRow };
        fixed (uint* pcPtr = pc)
        {
            VulkanApi.vkCmdPushConstants(cmdBuf, _pipeline.Layout, VkShaderStageFlags.Compute, 0, PushConstantBytes, (nint)pcPtr);
        }

        VulkanApi.vkCmdDispatch(cmdBuf, (uint)((m + Tile - 1) / Tile), (uint)((n + Tile - 1) / Tile), 1);
        Interlocked.Increment(ref Dispatches);
    }

    /// <inheritdoc/>
    public void Dispose()
    {
        if (_disposed) return;
        _disposed = true;
        if (_descriptorPool != 0)
            VulkanApi.vkDestroyDescriptorPool(_device.Handle, _descriptorPool, 0);
        _pipeline.Dispose();
        _module.Dispose();
        _ownedCodebooks?.Dispose();
    }
}
