#!/usr/bin/env python3
"""Generates matmul_iq4_xs_f32_gemv_multi.comp and matmul_iq3_s_f32_gemv_multi.comp (#902) from the single-row decode shaders.

Why generated, and why scalars: written with `float acc[NC]` and `for (cc < NC)` loops the shaders ran 10x slower from NC = 5 up (IQ4_XS 10240x2560:
115 us at n = 4, 836 us at n = 5, 2.6 ms at n = 8 on gfx1151). The column count is a specialization constant, the driver does not unroll the loops
(even with [[unroll]]) and so indexes the accumulator arrays dynamically, i.e. in scratch memory. Here every column is its own scalar guarded by
`if (NC > c)`, which the specializer folds away, so only the registers of the live columns remain.

Usage: python gen_iq_gemv_multi.py   (writes next to this script's shaders/ directory; recompile with glslc --target-env=vulkan1.2)
"""
import os

COLS = 16   # IQ4_XS; IQ3_S stays at IQ3S_COLS (below)
IQ3S_COLS = 8   # #1377: IQ3_S at 12/16 columns spills (18-23 ms vs 3.8 ms for two 8-column dispatches at 17408x5120), so it stops at 8
here = os.path.dirname(os.path.abspath(__file__))
sdir = os.path.join(here, 'shaders')


def cols(fmt, sep='\n'):
    """fmt may use {c}; emits it for every column."""
    return sep.join(fmt.format(c=c) for c in range(COLS))


def guarded(body, indent):
    """Wraps body (using {c}) as `if (NC > {c}u) { ... }` for every column."""
    lines = []
    for c in range(COLS):
        lines.append(f'{indent}if (NC > {c}u) {{')
        for ln in body.splitlines():
            lines.append(f'{indent}    ' + ln.format(c=c))
        lines.append(f'{indent}}}')
    return '\n'.join(lines)


REDUCE = '''    {partials_fill}
    barrier();
    for (uint stride = threads >> 1u; stride > 0u; stride >>= 1u) {{
        if (tid < stride) {{
{partials_add}
        }}
        barrier();
    }}

    if (tid < NC) y[tid * pc.M + m] = partials[tid][0];
}}
'''


def reduce_block():
    fill = '\n    '.join(f'if (NC > {c}u) partials[{c}][tid] = acc{c};' for c in range(COLS))
    add = '\n'.join(f'            if (NC > {c}u) partials[{c}][tid] += partials[{c}][tid + stride];' for c in range(COLS))
    return REDUCE.format(partials_fill=fill, partials_add=add)


def iq4_xs():
    src = open(os.path.join(sdir, 'matmul_iq4_xs_f32_gemv.comp'), encoding='utf-8').read()
    head_end = src.index('layout(local_size_x = 128')
    out = src[:head_end]
    out = out.replace('#version 450\n', '#version 450\n// IQ4_XS multi-column GEMV (2..16 activation rows, #902): Y[col, m] = sum_k W_iq4xs[m, k] * X[col, k].\n//\n'
                      '// GENERATED by native/vulkan/gen_iq_gemv_multi.py (do not edit): matmul_iq4_xs_f32_gemv.comp for NC columns at once. Each (super-block, sub-block)\n'
                      '// work item decodes its scale and codebook values ONCE and FMAs them against all NC FP32 activation rows; NC is a specialization constant,\n'
                      '// X is [NC, K], Y is [NC, M]. Every column has its own scalar accumulator (see the generator for why arrays were 10x slower from NC = 5).\n//\n', 1)
    out += '''layout(local_size_x = 128, local_size_y = 1, local_size_z = 1) in;

layout(constant_id = 0) const uint NC = 16u;   // default 16 so constant column indices validate; pipelines specialise it

layout(set = 0, binding = 0, std430) readonly  buffer BufW { uint  weight[]; };
layout(set = 0, binding = 1, std430) readonly  buffer BufX { float x[]; };       // [NC, K]
layout(set = 0, binding = 2, std430) writeonly buffer BufY { float y[]; };       // [NC, M]

layout(push_constant) uniform PushConstants {
    uint M;
    uint K;             // multiple of 256
    uint blocksPerRow;  // = K / 256
    uint rowUints;
} pc;

const uint IQ4_XS_BLOCK_BYTES     = 136u;
const uint IQ4_XS_GROUP_SIZE      = 256u;
const uint IQ4_XS_SUB_BLOCK_SIZE  = 32u;
const uint IQ4_XS_NUM_SUB_BLOCKS  = 8u;

const float KVALUES_IQ4NL[16] = float[16](
    -127.0, -104.0, -83.0, -65.0, -49.0, -35.0, -22.0, -10.0,
       1.0,   13.0,  25.0,  38.0,  53.0,  69.0,  89.0, 113.0
);

uint readByte(uint absByteOff) {
    uint u = weight[absByteOff >> 2u];
    uint shift = (absByteOff & 3u) * 8u;
    return (u >> shift) & 0xFFu;
}

float readHalf(uint absByteOff) {
    uint alignedIdx = absByteOff >> 2u;
    uint byteInWord = absByteOff & 3u;
    uint u = weight[alignedIdx];
    uint half16;
    if (byteInWord <= 2u) {
        half16 = (u >> (byteInWord * 8u)) & 0xFFFFu;
    } else {
        uint uNext = weight[alignedIdx + 1u];
        half16 = ((u >> 24) & 0xFFu) | ((uNext & 0xFFu) << 8);
    }
    return unpackHalf2x16(half16).x;
}

shared float partials[NC][128];

void main() {
    uint m = gl_WorkGroupID.x;
    if (m >= pc.M) return;

    uint tid = gl_LocalInvocationID.x;
    uint threads = gl_WorkGroupSize.x;

    uint rowByteStride = pc.blocksPerRow * IQ4_XS_BLOCK_BYTES;
    uint rowByteBase = m * rowByteStride;

''' + cols('    float acc{c} = 0.0;') + '''

    // One work item = one (super-block, sub-block) pair.
    uint workItems = pc.blocksPerRow * IQ4_XS_NUM_SUB_BLOCKS;
    for (uint work = tid; work < workItems; work += threads) {
        uint b = work / IQ4_XS_NUM_SUB_BLOCKS;
        uint ib = work % IQ4_XS_NUM_SUB_BLOCKS;
        uint blockByteBase = rowByteBase + b * IQ4_XS_BLOCK_BYTES;
        float d = readHalf(blockByteBase);
        uint scalesH = (readByte(blockByteBase + 2u))
                     | (readByte(blockByteBase + 3u) << 8u);
        uint scalesLBase = blockByteBase + 4u;
        uint qsBase      = blockByteBase + 8u;
        uint xBase = b * IQ4_XS_GROUP_SIZE;

        uint scalesLByte = readByte(scalesLBase + (ib >> 1u));
        uint low  = (scalesLByte >> (4u * (ib & 1u))) & 0xFu;
        uint high = (scalesH >> (2u * ib)) & 0x3u;
        int  ls   = int(low | (high << 4u)) - 32;
        float dl  = d * float(ls);

        uint subQsUint = (qsBase + ib * 16u) >> 2u;
        uint subXBase  = xBase + ib * IQ4_XS_SUB_BLOCK_SIZE;

''' + cols('        float lo{c} = 0.0; float hi{c} = 0.0;') + '''
        for (uint w = 0u; w < 4u; w++) {
            uint cur = weight[subQsUint + w];
            uint e = w * 4u;
            float k0 = KVALUES_IQ4NL[ cur        & 0xFu];
            float k1 = KVALUES_IQ4NL[(cur >>  8u) & 0xFu];
            float k2 = KVALUES_IQ4NL[(cur >> 16u) & 0xFu];
            float k3 = KVALUES_IQ4NL[(cur >> 24u) & 0xFu];
            float h0 = KVALUES_IQ4NL[(cur >>  4u) & 0xFu];
            float h1 = KVALUES_IQ4NL[(cur >> 12u) & 0xFu];
            float h2 = KVALUES_IQ4NL[(cur >> 20u) & 0xFu];
            float h3 = KVALUES_IQ4NL[(cur >> 28u) & 0xFu];
''' + guarded('uint xo{c} = {c}u * pc.K + subXBase + e;\n'
              'lo{c} += x[xo{c} + 0u] * k0 + x[xo{c} + 1u] * k1 + x[xo{c} + 2u] * k2 + x[xo{c} + 3u] * k3;\n'
              'hi{c} += x[xo{c} + 16u] * h0 + x[xo{c} + 17u] * h1 + x[xo{c} + 18u] * h2 + x[xo{c} + 19u] * h3;', '            ').replace('{c}', '{c}') + '''
        }
''' + cols('        if (NC > {c}u) acc{c} += dl * (lo{c} + hi{c});') + '''
    }

''' + reduce_block()
    out = out.replace('{c}', '')  # no stray template markers
    return out


def iq4_xs_coalesced():
    """Coalesced lane = K-position layout (as matmul_iq4_xs_mmvq.comp): one 32-lane subgroup per output row, lane L reads qs word L of the super-block
    (sub-block L / 4, word L % 4) and two vec4 of each activation row, so every load instruction is contiguous across lanes. The first version of this
    kernel kept the single-row shader's one-work-item-per-thread mapping, whose activation loads are 128 bytes apart per lane: harmless for one column,
    but at 5+ columns the working set left the L1 and the kernel slowed 5-20x (IQ4_XS 10240x2560: 133 us at n = 4, 582 us at n = 5, 2 ms at n = 8)."""
    head = '''#version 450
#extension GL_KHR_shader_subgroup_basic      : require
#extension GL_KHR_shader_subgroup_arithmetic : require
// IQ4_XS multi-column GEMV (2..16 activation rows, #902): Y[col, m] = sum_k W_iq4xs[m, k] * X[col, k].
//
// GENERATED by native/vulkan/gen_iq_gemv_multi.py (do not edit). F32 activations, coalesced lane = K-position layout (see the generator for why):
// one wave32 subgroup per output row; per super-block lane L decodes the 8 weights of qs word L (sub-block L / 4: 4 low-nibble elements
// [4w .. 4w+3] and 4 high-nibble elements [16+4w ..]) ONCE and FMAs them against all NC activation rows (two vec4 loads per row). NC is a
// specialization constant; every column has its own scalar accumulator. X is [NC, K], Y is [NC, M].
//
// IQ4_XS super-block (136 bytes / 256 elements): [0,1] fp16 d, [2,3] scales_h, [4..7] scales_l[4], [8..135] qs[128]
//   (8 sub-blocks x 16 bytes; low nibble -> element j, high nibble -> element j + 16 of the sub-block).
//   sub-block ib: ls = ((scales_l[ib / 2] >> (4 * (ib & 1))) & 0xF) | (((scales_h >> (2 * ib)) & 3) << 4);  dl = d * (ls - 32).

layout(local_size_x = 32, local_size_y = 1, local_size_z = 1) in;

layout(constant_id = 0) const uint NC = 16u;   // default 16 so constant column indices validate; pipelines specialise it

layout(set = 0, binding = 0, std430) readonly  buffer BufW { uint  weight[]; };
layout(set = 0, binding = 1, std430) readonly  buffer BufX { vec4  x4[]; };      // [NC, K/4]
layout(set = 0, binding = 2, std430) writeonly buffer BufY { float y[]; };       // [NC, M]

layout(push_constant) uniform PushConstants {
    uint M;
    uint K;             // multiple of 256
    uint blocksPerRow;  // = K / 256
    uint rowUints;
} pc;

const uint IQ4_XS_BLOCK_BYTES = 136u;

const float KV[16] = float[16](
    -127.0, -104.0, -83.0, -65.0, -49.0, -35.0, -22.0, -10.0,
       1.0,   13.0,  25.0,  38.0,  53.0,  69.0,  89.0, 113.0
);

uint readByte(uint absByteOff) {
    uint u = weight[absByteOff >> 2u];
    return (u >> ((absByteOff & 3u) * 8u)) & 0xFFu;
}

float readHalf(uint absByteOff) {
    uint alignedIdx = absByteOff >> 2u;
    uint byteInWord = absByteOff & 3u;
    uint u = weight[alignedIdx];
    uint half16;
    if (byteInWord <= 2u) {
        half16 = (u >> (byteInWord * 8u)) & 0xFFFFu;
    } else {
        uint uNext = weight[alignedIdx + 1u];
        half16 = ((u >> 24) & 0xFFu) | ((uNext & 0xFFu) << 8);
    }
    return unpackHalf2x16(half16).x;
}

void main() {
    uint m = gl_WorkGroupID.x;
    if (m >= pc.M) return;

    uint lane = gl_LocalInvocationID.x;   // 0..31
    uint ib = lane >> 2u;                 // sub-block 0..7
    uint w  = lane & 3u;                  // qs word within the sub-block
    uint xRow4 = pc.K >> 2u;              // vec4 per activation row

    uint rowByteBase = m * pc.blocksPerRow * IQ4_XS_BLOCK_BYTES;

'''
    mid = '''
    for (uint blk = 0u; blk < pc.blocksPerRow; blk++) {
        uint blockByteBase = rowByteBase + blk * IQ4_XS_BLOCK_BYTES;
        float d = readHalf(blockByteBase);
        uint scalesH = readByte(blockByteBase + 2u) | (readByte(blockByteBase + 3u) << 8u);
        uint scalesLByte = readByte(blockByteBase + 4u + (ib >> 1u));
        uint low  = (scalesLByte >> (4u * (ib & 1u))) & 0xFu;
        uint high = (scalesH >> (2u * ib)) & 0x3u;
        float dl = d * float(int(low | (high << 4u)) - 32);

        uint cur = weight[((blockByteBase + 8u) >> 2u) + lane];
        vec4 wl = vec4(KV[ cur        & 0xFu], KV[(cur >>  8u) & 0xFu], KV[(cur >> 16u) & 0xFu], KV[(cur >> 24u) & 0xFu]);
        vec4 wh = vec4(KV[(cur >>  4u) & 0xFu], KV[(cur >> 12u) & 0xFu], KV[(cur >> 20u) & 0xFu], KV[(cur >> 28u) & 0xFu]);

        uint xi = blk * 64u + ib * 8u + w;   // vec4 index of x[256 blk + 32 ib + 4 w]
'''
    col_body = guarded('vec4 xl{c} = x4[{c}u * xRow4 + xi];\nvec4 xh{c} = x4[{c}u * xRow4 + xi + 4u];\nacc{c} += dl * (dot(wl, xl{c}) + dot(wh, xh{c}));', '        ')
    tail = '''
    }

''' + '\n'.join(f'    float sum{c} = (NC > {c}u) ? subgroupAdd(acc{c}) : 0.0;' for c in range(COLS)) + '''
    if (subgroupElect()) {
''' + '\n'.join(f'        if (NC > {c}u) y[{c}u * pc.M + m] = sum{c};' for c in range(COLS)) + '''
    }
}
'''
    return head + cols('    float acc{c} = 0.0;') + '\n' + mid + col_body + tail


def iq3_s():
    global COLS
    COLS = IQ3S_COLS
    src = open(os.path.join(sdir, 'matmul_iq3_s_f32_gemv.comp'), encoding='utf-8').read()
    head_end = src.index('layout(local_size_x = 128')
    out = src[:head_end]
    out = out.replace('#version 450\n', '#version 450\n// IQ3_S multi-column GEMV (2..8 activation rows, #902): Y[col, m] = sum_k W_iq3s[m, k] * X[col, k].\n//\n'
                      '// GENERATED by native/vulkan/gen_iq_gemv_multi.py (do not edit): matmul_iq3_s_f32_gemv.comp for NC columns at once. The grid-codebook gathers and\n'
                      "// sign decode (the expensive part) run ONCE per weight and the decoded values are FMA'd against all NC FP32 activation rows; NC is a\n"
                      '// specialization constant, X is [NC, K], Y is [NC, M]. Every column has its own scalar accumulator (see the generator).\n//\n', 1)
    body_cols = guarded('uint xo{c} = {c}u * pc.K + xOff + j;\n'
                        'pair{c} += w0 * x[xo{c}];\n'
                        'pair{c} += wH * x[xo{c} + 4u];', '                    ')
    out += '''layout(local_size_x = 128, local_size_y = 1, local_size_z = 1) in;

layout(constant_id = 0) const uint NC = 8u;   // default 8 so constant column indices validate; pipelines specialise it

layout(set = 0, binding = 0, std430) readonly  buffer BufW       { uint  weight[]; };
layout(set = 0, binding = 1, std430) readonly  buffer BufX       { float x[]; };       // [NC, K]
layout(set = 0, binding = 2, std430) writeonly buffer BufY       { float y[]; };       // [NC, M]
layout(set = 0, binding = 3, std430) readonly  buffer BufGrid    { uint  iq3sGrid[]; };

layout(push_constant) uniform PushConstants {
    uint M;
    uint K;
    uint blocksPerRow;
    uint rowUints;
} pc;

const uint IQ3_S_BLOCK_BYTES = 110u;
const uint IQ3_S_GROUP_SIZE  = 256u;
const uint NUM_SUBBLOCKS     = 8u;

uint readByte(uint absByteOff) {
    uint u = weight[absByteOff >> 2u];
    uint shift = (absByteOff & 3u) * 8u;
    return (u >> shift) & 0xFFu;
}

uint read4Bytes(uint absByteOff) {
    uint idx = absByteOff >> 2u;
    uint ph  = absByteOff & 3u;
    uint lo  = weight[idx];
    if (ph == 0u) return lo;
    uint hi = weight[idx + 1u];
    return (lo >> (ph * 8u)) | (hi << ((4u - ph) * 8u));
}

float readHalf(uint absByteOff) {
    uint alignedIdx = absByteOff >> 2u;
    uint byteInWord = absByteOff & 3u;
    uint u = weight[alignedIdx];
    uint half16;
    if (byteInWord <= 2u) {
        half16 = (u >> (byteInWord * 8u)) & 0xFFFFu;
    } else {
        uint uNext = weight[alignedIdx + 1u];
        half16 = ((u >> 24) & 0xFFu) | ((uNext & 0xFFu) << 8);
    }
    return unpackHalf2x16(half16).x;
}

uint gridByte(uint absIdx) {
    uint u = iq3sGrid[absIdx >> 2u];
    return (u >> ((absIdx & 3u) * 8u)) & 0xFFu;
}

shared float partials[NC][128];

void main() {
    uint m = gl_WorkGroupID.x;
    if (m >= pc.M) return;

    uint tid = gl_LocalInvocationID.x;
    uint threads = gl_WorkGroupSize.x;

    uint rowByteStride = pc.blocksPerRow * IQ3_S_BLOCK_BYTES;
    uint rowByteBase   = m * rowByteStride;

''' + cols('    float acc{c} = 0.0;') + '''

    // One work item = one (super-block, sub-block) pair.
    uint workItems = pc.blocksPerRow * NUM_SUBBLOCKS;
    for (uint work = tid; work < workItems; work += threads) {
        uint b = work / NUM_SUBBLOCKS;
        uint ib32 = work % NUM_SUBBLOCKS;
        uint blockByteBase = rowByteBase + b * IQ3_S_BLOCK_BYTES;
        float d = readHalf(blockByteBase);
        uint qsBase     = blockByteBase + 2u;
        uint qhBase     = blockByteBase + 2u + IQ3_S_GROUP_SIZE / 4u;
        uint signsBase  = blockByteBase + 2u + IQ3_S_GROUP_SIZE / 4u + IQ3_S_GROUP_SIZE / 32u;
        uint scalesBase = blockByteBase + 2u + IQ3_S_GROUP_SIZE / 4u + IQ3_S_GROUP_SIZE / 32u + IQ3_S_GROUP_SIZE / 8u;
        uint xBase      = b * IQ3_S_GROUP_SIZE;

        uint scalesW = read4Bytes(scalesBase);
        uint qh0     = read4Bytes(qhBase);
        uint qh1     = read4Bytes(qhBase + 4u);

        uint scaleByte = (scalesW >> ((ib32 >> 1u) * 8u)) & 0xFFu;
        uint subScale  = ((ib32 & 1u) == 0u) ? (scaleByte & 0xFu) : (scaleByte >> 4u);
        float db = d * float(1u + 2u * subScale);
        uint qhByte    = ((ib32 < 4u) ? (qh0 >> (ib32 * 8u))
                                      : (qh1 >> ((ib32 - 4u) * 8u))) & 0xFFu;
        uint qsSubBase = qsBase + ib32 * 8u;
        uint sgSubBase = signsBase + ib32 * 4u;
        uint xSubBase  = xBase + ib32 * 32u;

        uint qsw0  = read4Bytes(qsSubBase);
        uint qsw1  = read4Bytes(qsSubBase + 4u);
        uint signsW = read4Bytes(sgSubBase);

        for (uint l = 0u; l < 4u; l++) {
            uint qsw = (l < 2u) ? qsw0 : qsw1;
            uint sh  = (l & 1u) * 16u;
            uint lo1 = (qsw >> sh) & 0xFFu;
            uint lo2 = (qsw >> (sh + 8u)) & 0xFFu;
            uint hi1 = (qhByte << (8u - 2u * l)) & 0x100u;
            uint hi2 = (qhByte << (7u - 2u * l)) & 0x100u;
            uint g1  = lo1 | hi1;
            uint g2  = lo2 | hi2;
            uint signs = (signsW >> (l * 8u)) & 0xFFu;
            uint xOff0 = xSubBase + l * 8u;
            uint gOff1 = g1 * 4u;
            uint gOff2 = g2 * 4u;

''' + cols('            float pair{c} = 0.0;') + '''
            for (uint j = 0u; j < 4u; j++) {
                float g0 = float(gridByte(gOff1 + j));
                float gH = float(gridByte(gOff2 + j));
                float s0 = ((signs & (1u << (j + 0u))) != 0u) ? -1.0 : 1.0;
                float sH = ((signs & (1u << (j + 4u))) != 0u) ? -1.0 : 1.0;
                float w0 = g0 * s0;
                float wH = gH * sH;
                uint xOff = xOff0;
''' + body_cols + '''
            }
''' + cols('            if (NC > {c}u) acc{c} += db * pair{c};') + '''
        }
    }

''' + reduce_block()
    return out


if __name__ == '__main__':
    for name, text in (('matmul_iq4_xs_f32_gemv_multi.comp', iq4_xs_coalesced()), ('matmul_iq3_s_f32_gemv_multi.comp', iq3_s())):
        with open(os.path.join(sdir, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', name, len(text))
