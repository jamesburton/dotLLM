#!/usr/bin/env python3
"""Writes the thin .comp wrappers of the Inkling 2 Vulkan kernels (#2034): one per (body, weight type, activation arm).

Each wrapper is `#version 450`, the include extension, its defines and `#include "inkling2_<body>.glsl"`. The `_f32act` twin defines ACT_F32 and builds
the F32-activation-storage REFERENCE arm (a control compared against the CPU reference; never selected by default). Mirrors gen_olala_wrappers.py.
Run from anywhere; rewrites shaders/inkling2_*.comp (inkling2_softcap.comp is hand-written and untouched).
"""
import os

SHADERS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shaders")

BODIES = {
    "embed": [None],
    "rmsnorm": [None],
    "mix": [None],
    "ctrl_in": [None],
    "ctrl_out": [None],
    "conv": [None],
    "qkprep": [None],
    "attn": [None],
    "moe_gate_up": ["nvfp4", "q8_0"],
    "moe_down": ["nvfp4", "q8_0"],
}

for body, types in BODIES.items():
    for t in types:
        for f32 in (False, True):
            name = "inkling2_" + body + (("_" + t) if t else "") + ("_f32act" if f32 else "")
            lines = ["#version 450",
                     f"// Generated by native/vulkan/gen_inkling2_wrappers.py; body: inkling2_{body}.glsl (issue #2034)."
                     + (" F32-activation reference arm." if f32 else " BF16 activations."),
                     "#extension GL_GOOGLE_include_directive : require"]
            if f32:
                lines.append("#define ACT_F32 1")
            if t:
                lines.append(f"#define WT_{t.upper()} 1")
            lines.append(f'#include "inkling2_{body}.glsl"')
            with open(os.path.join(SHADERS, name + ".comp"), "w", newline="\n") as fh:
                fh.write("\n".join(lines) + "\n")
print("done")
