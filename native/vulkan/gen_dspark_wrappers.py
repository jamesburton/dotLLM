#!/usr/bin/env python3
"""Writes the thin .comp wrappers of the Inkling 2 Vulkan DSpark shaders (#2046 / #2075): one per (body, activation arm [, F16 logits]).

BF16 activations are the plain name, `_f16act` the F16 activation twin (the default activation format since #2075). The bodies are shaders/inkling2_dspark_*.glsl.
Run from anywhere; rewrites the wrappers (the markov_logits family and olala_gemv_q8_0_f16out_f16act.comp included).
"""
import os

SHADERS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shaders")
BODIES = ["attn", "ctxmix", "eltwise", "headnorm", "markov_pre", "markov_step"]


def write(name, body, defs, note):
    lines = ["#version 450", f"// Generated by native/vulkan/gen_dspark_wrappers.py; body: {body}.glsl (issue #2046 / #2075). {note}",
             "#extension GL_GOOGLE_include_directive : require"] + defs + [f'#include "{body}.glsl"']
    with open(os.path.join(SHADERS, name + ".comp"), "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


for b in BODIES:
    body = "inkling2_dspark_" + b
    write(body, body, [], "BF16 activations.")
    write(body + "_f16act", body, ["#define ACT_F16 1"], "F16 activations.")
body = "inkling2_dspark_markov_logits"
write(body, body, [], "BF16 activations, F32 logits.")
write(body + "_f16", body, ["#define LOGITS_F16 1"], "BF16 activations, F16 logits.")
write(body + "_f16act", body, ["#define ACT_F16 1"], "F16 activations, F32 logits.")
write(body + "_f16_f16act", body, ["#define ACT_F16 1", "#define LOGITS_F16 1"], "F16 activations, F16 logits.")
print("done")
