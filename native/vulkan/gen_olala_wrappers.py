#!/usr/bin/env python3
"""Writes the thin .comp wrappers of the Olala Vulkan kernels (#1983): one per (body, weight/embedding type, activation arm).

Each wrapper is `#version 450`, the include extension, its defines and `#include "olala_<body>.glsl"`. The `_f32act` twin defines ACT_F32 and builds
the F32-activation-storage REFERENCE arm (a test/measurement control for the precision sign-off, never selected by default).
Run from anywhere; rewrites shaders/olala_*.comp.
"""
import os

SHADERS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shaders")

BODIES = {
    "gemv": ["q8_0", "q6_k", "bf16"],
    "moe_up": ["q8_0", "q6_k", "bf16"],
    "moe_down": ["q8_0", "q6_k", "bf16"],
    "embed": ["q8_0", "bf16"],
    "moe_route": [None],
    "geodesic": [None],
    "mamba3_step": [None],
    "tpa_kv": [None],
    "tpa_attn": [None],
}

# F16 measurement twins (Inkling 2 shares these bodies with Olala): (body, weight type)
F16_TWINS = {("gemv", "q8_0"), ("gemv", "bf16"), ("moe_route", None)}

for body, types in BODIES.items():
    for t in types:
        for arm in ("", "f32act", "f16act"):
            f32 = arm == "f32act"
            if arm == "f16act" and (body, t) not in F16_TWINS:
                continue   # only the kernels the Inkling 2 Vulkan forward shares get an F16 measurement twin
            name = "olala_" + body + (("_" + t) if t else "") + (("_" + arm) if arm else "")
            lines = ["#version 450",
                     f"// Generated by native/vulkan/gen_olala_wrappers.py; body: olala_{body}.glsl (issue #1983)."
                     + {"": " BF16 activations.", "f32act": " F32-activation reference arm.",
                        "f16act": " F16-activation measurement arm (Inkling 2 activation-precision study; Olala must not use it)."}[arm],
                     "#extension GL_GOOGLE_include_directive : require"]
            if f32:
                lines.append("#define ACT_F32 1")
            if arm == "f16act":
                lines.append("#define ACT_F16 1")
            if t:
                macro = ("EMB_" if body == "embed" else "WT_") + t.upper()
                lines.append(f"#define {macro} 1")
            lines.append(f'#include "olala_{body}.glsl"')
            with open(os.path.join(SHADERS, name + ".comp"), "w", newline="\n") as fh:
                fh.write("\n".join(lines) + "\n")
print("done")
