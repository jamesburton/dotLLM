#!/usr/bin/env python3
"""Writes the thin .comp wrappers of the Inkling 2 Vulkan vision tower (#2062 / #2075): one per (body, activation arm [, F32 RoPE table]).

Each wrapper is `#version 450`, the include extension, its defines and `#include "<body>.glsl"`. The default (no suffix) is the BF16 arm; `_f16act` stores F16 activations (the default
activation format since #2075 is selected on the host), `_f32act` is the F32 measurement arm, `_rope32` (GEMM only) reads the RoPE table as F32 (measurement arm).
Run from anywhere; rewrites shaders/vit_*.comp.
"""
import os

SHADERS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shaders")
BODIES = ["vit_cls", "vit_layernorm", "vit_patch_embd", "vit_attn", "vit_gemm_q8"]
ARMS = [("", []), ("_f16act", ["#define ACT_F16 1"]), ("_f32act", ["#define ACT_F32 1"])]

for body in BODIES:
    for suffix, defs in ARMS:
        for rope in ([False, True] if body == "vit_gemm_q8" else [False]):
            name = body + suffix + ("_rope32" if rope else "")
            lines = ["#version 450", f"// Generated by native/vulkan/gen_vit_wrappers.py; body: {body}.glsl (issue #2062 / #2075).",
                     "#extension GL_GOOGLE_include_directive : require"] + defs + (["#define ROPE_F32 1"] if rope else []) + [f'#include "{body}.glsl"']
            with open(os.path.join(SHADERS, name + ".comp"), "w", newline="\n") as fh:
                fh.write("\n".join(lines) + "\n")
print("done")
