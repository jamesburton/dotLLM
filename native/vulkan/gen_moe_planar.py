#!/usr/bin/env python3
"""Generates the PLANAR Q2_0 indexed MMVQ shader for the Edge0 MTP head (G6, #1990): native/vulkan/shaders/moe_indexed_matmul_q2_0_planar_mmvq.comp.

The Edge0 draft head ships its 512 routed experts in edge0-strata's planar layout (tools/mtp_rt.py blob_of): per expert one blob
  [gate/up codes | down codes | gate/up fp16 scales | down fp16 scales]   (gate and up rows interleaved: row 2r = gate r, 2r+1 = up r),
a lossless relayout of ggml Q2_0 blocks (fp16 d + 16 code bytes per 64 elements). This script takes the contiguous-bank shader
moe_indexed_matmul_q2_0_mmvq.comp and changes ONLY the address of a block's scale and codes, so the dp4a math cannot drift:
  block index  = (m * rowMul + rowAdd) * blocksPerRow + blk
  scale at     = expert * expertStride + scaleBase + blockIdx * 2
  codes at     = expert * expertStride + codeBase  + blockIdx * 16 + 2 * slice

Run from the repo root: python native/vulkan/gen_moe_planar.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = os.path.join(HERE, 'shaders')


def rep(s, old, new):
    assert s.count(old) == 1, old
    return s.replace(old, new)


def main():
    src = 'moe_indexed_matmul_q2_0_mmvq'
    s = open(os.path.join(SHADERS, src + '.comp'), newline='', encoding='utf-8').read().replace('\r\n', '\n')
    s = rep(s, '    uint xDiv;          // activation row = n / xDiv (1 = per-row input; topK = one row broadcast to its topK expert slots)\n} pc;',
            '    uint xDiv;          // activation row = n / xDiv (1 = per-row input; topK = one row broadcast to its topK expert slots)\n'
            '    uint expertStride;  // PLANAR variant: bytes between two experts\' blobs\n'
            '    uint codeBase;      // byte offset of this projection\'s code plane inside a blob\n'
            '    uint scaleBase;     // byte offset of this projection\'s fp16 scale plane inside a blob\n'
            '    uint rowMul;        // stored row = m * rowMul + rowAdd (2 / 0 = gate, 2 / 1 = up of the interleaved gate/up planes; 1 / 0 = down)\n'
            '    uint rowAdd;\n} pc;')
    s = rep(s, '    uint rowByteBase = (expert * pc.M + m) * pc.blocksPerRow * Q2_0_BLOCK_BYTES;',
            '    uint expertBase  = expert * pc.expertStride;\n    uint rowBlock0   = (m * pc.rowMul + pc.rowAdd) * pc.blocksPerRow;')
    s = rep(s, '        uint blockByteBase = rowByteBase + blk * Q2_0_BLOCK_BYTES;\n'
               '        float d = unpackHalf2x16(readHalf16(blockByteBase)).x;\n'
               '        uint h = readHalf16(blockByteBase + 2u + 2u * sl);   // 8 two-bit codes',
            '        uint blockIdx = rowBlock0 + blk;\n'
            '        float d = unpackHalf2x16(readHalf16(expertBase + pc.scaleBase + blockIdx * 2u)).x;\n'
            '        uint h = readHalf16(expertBase + pc.codeBase + blockIdx * 16u + 2u * sl);   // 8 two-bit codes')
    banner = ('// PLANAR variant (Edge0 MTP head, G6 #1990), GENERATED by native/vulkan/gen_moe_planar.py from %s.comp - edit the source / the generator, not this file.\n'
              '// Experts are edge0-strata blobs [gate/up codes | down codes | gate/up scales | down scales]; see the generator for the address rule.\n' % src)
    lines = s.split('\n')
    last_ext = max(i for i, l in enumerate(lines) if l.startswith('#extension'))
    lines.insert(last_ext + 1, banner.rstrip('\n'))
    out = os.path.join(SHADERS, 'moe_indexed_matmul_q2_0_planar_mmvq.comp')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', out)


if __name__ == '__main__':
    main()
