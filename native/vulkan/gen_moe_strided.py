#!/usr/bin/env python3
"""Generates the record-STRIDED expert-bank shaders for Edge0 (G3, #1981): native/vulkan/shaders/*_strided.comp.

An Edge0 pack stores each expert as one fixed-size record (gate | up | down, 1,630,720 B for the Q3_K build). The strided variants read a projection
in place from the mmap'd record array: expert e's rows start at  baseOffset + e * expertStride  (bytes) instead of  e * M * rowBytes.  Everything else
(lane layout, dequant, dp4a / coopmat math) is the unmodified source shader, so the two cannot drift: this script applies exactly two textual changes
(two extra push constants, the row-base expression) and asserts each matched once.

Sources -> outputs: moe_indexed_matmul_{q3_k,iq4_nl}_mmvq[_v2], moe_grouped_matmul_{q3_k,iq4_nl}_coopmat_m64 (+ _strided).
Run from the repo root: python native/vulkan/gen_moe_strided.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = os.path.join(HERE, 'shaders')


def rep(s, old, new):
    assert s.count(old) == 1, old
    return s.replace(old, new)


def indexed(src, out, block_const):
    s = open(os.path.join(SHADERS, src + '.comp'), newline='', encoding='utf-8').read().replace('\r\n', '\n')
    s = rep(s, '    uint xDiv;          // activation row = n / xDiv (1 = per-row input; topK = one row broadcast to its topK expert slots)\n} pc;',
            '    uint xDiv;          // activation row = n / xDiv (1 = per-row input; topK = one row broadcast to its topK expert slots)\n'
            '    uint expertStride;  // STRIDED variant: byte distance between two experts of the bank (the pack record size)\n'
            '    uint baseOffset;    // STRIDED variant: byte offset of the projection inside expert 0\'s record\n} pc;')
    s = rep(s, '    uint rowByteBase = (expert * pc.M + m) * pc.blocksPerRow * %s;' % block_const,
            '    uint rowByteBase = pc.baseOffset + expert * pc.expertStride + m * (pc.blocksPerRow * %s);' % block_const)
    banner = ('// STRIDED variant (Edge0 G3, #1981), GENERATED by native/vulkan/gen_moe_strided.py from %s.comp - edit the source / the generator, not this file.\n'
              '// Expert e of the bank starts at pc.baseOffset + e * pc.expertStride (bytes): the pack\'s fixed-size gate|up|down records are read in place.\n' % src)
    lines = s.split('\n')
    last_ext = max(i for i, l in enumerate(lines) if l.startswith('#extension'))
    lines.insert(last_ext + 1, banner.rstrip('\n'))
    open(os.path.join(SHADERS, out + '.comp'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', out)


def grouped(src, out):
    s = open(os.path.join(SHADERS, src + '.comp'), newline='', encoding='utf-8').read().replace('\r\n', '\n')
    s = rep(s, '    uint applyScale;    // unused (kept so the push-constant block matches the other grouped shaders)\n} pc;',
            '    uint applyScale;    // unused (kept so the push-constant block matches the other grouped shaders)\n'
            '    uint expertStride;  // STRIDED variant: byte distance between two experts of the bank (the pack record size)\n'
            '    uint baseOffset;    // STRIDED variant: byte offset of the projection inside expert 0\'s record\n} pc;')
    s = rep(s, '    uint rowBase = expert * pc.M * pc.rowBytes + mGlobal * pc.rowBytes;',
            '    uint rowBase = pc.baseOffset + expert * pc.expertStride + mGlobal * pc.rowBytes;')
    banner = ('// STRIDED variant (Edge0 G3, #1981), GENERATED by native/vulkan/gen_moe_strided.py from %s.comp - edit the source / the generator, not this file.\n'
              '// Expert e of the bank starts at pc.baseOffset + e * pc.expertStride (bytes): the pack\'s fixed-size gate|up|down records are read in place.\n' % src)
    s = s.replace('#version 450\n', '#version 450\n' + banner, 1)
    open(os.path.join(SHADERS, out + '.comp'), 'w', encoding='utf-8', newline='\n').write(s)
    print('wrote', out)


def main():
    indexed('moe_indexed_matmul_q3_k_mmvq', 'moe_indexed_matmul_q3_k_mmvq_strided', 'Q3K_BLOCK_BYTES')
    indexed('moe_indexed_matmul_iq4_nl_mmvq_v2', 'moe_indexed_matmul_iq4_nl_mmvq_v2_strided', 'IQ4_NL_BLOCK_BYTES')
    grouped('moe_grouped_matmul_q3_k_coopmat_m64', 'moe_grouped_matmul_q3_k_coopmat_m64_strided')
    grouped('moe_grouped_matmul_iq4_nl_coopmat_m64', 'moe_grouped_matmul_iq4_nl_coopmat_m64_strided')


if __name__ == '__main__':
    main()
