template <int QT>
__device__ __forceinline__ void moe_eg_gemv_impl(
    const uint8_t* const* __restrict__ w,
    const int* __restrict__ group_start,
    const int* __restrict__ slot_ids,
    const int* __restrict__ x_row,
    const float* __restrict__ X,
    float* __restrict__ Y,
    const int M,
    const int K,
    const int relu2)
{
    __shared__ uint8_t grid_s[QT == QT_IQ2_XXS ? 2048 : 1];
    if (QT == QT_IQ2_XXS)
    {
        for (int i = threadIdx.x; i < 2048; i += blockDim.x)
            grid_s[i] = iq2xxs_grid_moe[i];
        __syncthreads();
    }

    const int lane = threadIdx.x & 31;
    const int row = blockIdx.x * MOE_EG_WARPS + (threadIdx.x >> 5);
    const int g = blockIdx.y;
    if (row >= M) return; // whole warp: row is warp-uniform

    const int s0 = group_start[g], s1 = group_start[g + 1];
    const uint8_t* wr = w[g] + (size_t)row * row_bytes<QT>(K);
    const int nChunks = (K + 255) / 256; // Q8_0 rows may end in a partial chunk (K % 32 == 0)

    for (int base = s0; base < s1; base += MOE_EG_SLOTS)
    {
        const int ns = min(MOE_EG_SLOTS, s1 - base);
        const float* xr[MOE_EG_SLOTS];
        #pragma unroll
        for (int i = 0; i < MOE_EG_SLOTS; i++)
        {
            int s = i < ns ? slot_ids[base + i] : 0;
            int xi = x_row != nullptr ? x_row[s] : s;
            xr[i] = X + (size_t)xi * K;
        }

        float acc[MOE_EG_SLOTS];
        #pragma unroll
        for (int i = 0; i < MOE_EG_SLOTS; i++) acc[i] = 0.0f;

        for (int c = 0; c < nChunks; c++)
        {
            const int e0 = c * 256 + lane * 8;
            if (e0 >= K) continue;
            float v[8];
            deq8<QT>(wr, c, lane, v, grid_s);
            #pragma unroll
            for (int i = 0; i < MOE_EG_SLOTS; i++)
            {
                if (i < ns)
                {
                    const float4 a = *reinterpret_cast<const float4*>(xr[i] + e0);
                    const float4 b = *reinterpret_cast<const float4*>(xr[i] + e0 + 4);
                    acc[i] += v[0] * a.x + v[1] * a.y + v[2] * a.z + v[3] * a.w
                            + v[4] * b.x + v[5] * b.y + v[6] * b.z + v[7] * b.w;
                }
            }
        }

        #pragma unroll
        for (int i = 0; i < MOE_EG_SLOTS; i++)
        {
            if (i < ns) // ns is warp-uniform, so every lane takes part in the shuffles
            {
                float r = acc[i];
                for (int off = 16; off > 0; off >>= 1)
                    r += __shfl_down_sync(0xFFFFFFFF, r, off);
                if (lane == 0)
                {
                    if (relu2)
                    {
                        r = fmaxf(r, 0.0f);
                        r = r * r;
                    }
                    Y[(size_t)slot_ids[base + i] * M + row] = r;
                }
            }
        }
    }
}

