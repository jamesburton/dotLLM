// Nemotron-H MoE (nemotron_h_moe: Nemotron 3.5 Bolt / Lightning) routed-expert kernels, issue #403.
//
// The router runs on the host (RouteToken, shared with the CPU model), which builds a CSR schedule
// grouped by expert: G used experts, group_start[G+1] slot ranges into an ordered slot list, and one
// expert base pointer per group. A "slot" is one (token, k) pair, slot id = token * topK + k.
//
//   moe_eg_gemv_<qt>_f32  "expert-grouped GEMV": for group g and weight row r,
//       Y[slot, r] = act( sum_k W_g[r, k] * X[x_row[slot], k] )   for every slot of group g,
//       act = relu^2 (max(0, v)^2) when relu2 != 0, else identity.
//     grid = (ceil(M / MOE_EG_WARPS), G), block = 32 * MOE_EG_WARPS. Each warp owns one weight row;
//     lane l dequantises elements [l*8, l*8+8) of each 256-element super-block once per pass and
//     dots them with up to MOE_EG_SLOTS of the group's slots (passes loop over chunks of 8 slots).
//     x_row == nullptr means x_row[slot] = slot (the down projection reads the slot's own row).
//
//   moe_weighted_slot_sum_f32: acc[t, d] = sum_{k=0..topK-1} w[t*topK+k] * Yslot[t*topK+k, d], summed in
//     slot order k = 0..topK-1 with separate multiply and add (no FMA contraction), as the CPU does.
//
// Weight layouts follow ggml's dequantize_row_{q4_K,q5_K,q6_K,q8_0,iq2_xxs} (ggml-quants.c); the in-repo
// authorities are DotLLM.Cpu Dequantize* and native/kernels/{quantized_gemv,iq2}.cu. Every block size is
// even and every half / ushort field sits at an even offset, so the loads below use 16-bit reads only.

#include <cuda_fp16.h>
#include <stdint.h>

#define MOE_EG_WARPS 4
#define MOE_EG_SLOTS 8

#define QT_Q4_K 0
#define QT_Q5_K 1
#define QT_Q6_K 2
#define QT_Q8_0 3
#define QT_IQ2_XXS 4

__device__ __forceinline__ float ld_f16(const uint8_t* p)
{
    return __half2float(*reinterpret_cast<const half*>(p));
}

// 8 bytes from a 2-byte-aligned address.
__device__ __forceinline__ void ld8(const uint8_t* p, uint8_t out[8])
{
    const uint16_t* q = reinterpret_cast<const uint16_t*>(p);
    #pragma unroll
    for (int i = 0; i < 4; i++)
    {
        uint16_t v = q[i];
        out[2 * i] = (uint8_t)(v & 0xFF);
        out[2 * i + 1] = (uint8_t)(v >> 8);
    }
}

// 32-bit little-endian value from a 2-byte-aligned address.
__device__ __forceinline__ uint32_t ld_u32_a2(const uint8_t* p)
{
    const uint16_t* q = reinterpret_cast<const uint16_t*>(p);
    return (uint32_t)q[0] | ((uint32_t)q[1] << 16);
}

// ggml get_scale_min_k4: 6-bit scale and min of sub-block j (0..7) from the 12 packed scale bytes.
__device__ __forceinline__ void scale_min_k4(int j, const uint8_t* q, int& d, int& m)
{
    if (j < 4)
    {
        d = q[j] & 63;
        m = q[j + 4] & 63;
    }
    else
    {
        d = (q[j + 4] & 0xF) | ((q[j - 4] >> 6) << 4);
        m = (q[j + 4] >> 4) | ((q[j] >> 6) << 4);
    }
}

// Bytes of one weight row of K elements.
template <int QT>
__device__ __forceinline__ size_t row_bytes(int K)
{
    if (QT == QT_Q4_K) return (size_t)(K / 256) * 144;
    if (QT == QT_Q5_K) return (size_t)(K / 256) * 176;
    if (QT == QT_Q6_K) return (size_t)(K / 256) * 210;
    if (QT == QT_Q8_0) return (size_t)(K / 32) * 34;
    return (size_t)(K / 256) * 66; // IQ2_XXS
}

// Dequantises elements [c*256 + lane*8, +8) of weight row `wr` into v[0..7].
template <int QT>
__device__ __forceinline__ void deq8(const uint8_t* __restrict__ wr, int c, int lane, float v[8],
                                     const uint8_t* __restrict__ grid)
{
    if (QT == QT_Q4_K)
    {
        // block_q4_K: half d; half dmin; uint8 scales[12]; uint8 qs[128].
        // 64-element chunk j = lane/8; its first 32 elements are the low nibbles of qs[32j..32j+32),
        // the next 32 the high nibbles. Sub-block (32 elements) = lane/4.
        const uint8_t* b = wr + (size_t)c * 144;
        float d = ld_f16(b), dmin = ld_f16(b + 2);
        int sub = lane >> 2, j = lane >> 3, hi = sub & 1;
        int sc, m;
        scale_min_k4(sub, b + 4, sc, m);
        float dl = d * (float)sc, ml = dmin * (float)m;
        uint8_t q[8];
        ld8(b + 16 + 32 * j + 8 * (lane & 3), q);
        #pragma unroll
        for (int t = 0; t < 8; t++)
            v[t] = dl * (float)(hi ? (q[t] >> 4) : (q[t] & 0xF)) - ml;
    }
    else if (QT == QT_Q5_K)
    {
        // block_q5_K: half d; half dmin; uint8 scales[12]; uint8 qh[32]; uint8 qs[128].
        // As Q4_K, plus the 5th bit of element i of sub-block `sub` is bit `sub` of qh[i % 32].
        const uint8_t* b = wr + (size_t)c * 176;
        float d = ld_f16(b), dmin = ld_f16(b + 2);
        int sub = lane >> 2, j = lane >> 3, hi = sub & 1, i0 = 8 * (lane & 3);
        int sc, m;
        scale_min_k4(sub, b + 4, sc, m);
        float dl = d * (float)sc, ml = dmin * (float)m;
        uint8_t ql[8], qh[8];
        ld8(b + 48 + 32 * j + i0, ql);
        ld8(b + 16 + i0, qh);
        #pragma unroll
        for (int t = 0; t < 8; t++)
        {
            int lo = hi ? (ql[t] >> 4) : (ql[t] & 0xF);
            int h = (qh[t] >> sub) & 1;
            v[t] = dl * (float)(lo + (h << 4)) - ml;
        }
    }
    else if (QT == QT_Q6_K)
    {
        // block_q6_K: uint8 ql[128]; uint8 qh[64]; int8 scales[16]; half d.
        // 128-element half n; within it quarter q (32 elements) reads ql[64n + 32*(q&1) + i] nibble
        // (q>>1), qh[32n + i] bits 2q..2q+1, scale scales[8n + i/16 + 2q].
        const uint8_t* b = wr + (size_t)c * 210;
        float d = ld_f16(b + 208);
        int n = lane >> 4, qq = (lane & 15) >> 2, li = 8 * (lane & 3);
        uint8_t ql[8], qh[8];
        ld8(b + 64 * n + 32 * (qq & 1) + li, ql);
        ld8(b + 128 + 32 * n + li, qh);
        int shiftL = (qq >> 1) * 4, shiftH = 2 * qq;
        float dl = d * (float)((const int8_t*)(b + 192))[8 * n + (li >> 4) + 2 * qq];
        #pragma unroll
        for (int t = 0; t < 8; t++)
        {
            int q6 = ((ql[t] >> shiftL) & 0xF) | (((qh[t] >> shiftH) & 3) << 4);
            v[t] = dl * (float)(q6 - 32);
        }
    }
    else if (QT == QT_Q8_0)
    {
        // block_q8_0: half d; int8 qs[32]. A 256-element chunk is 8 blocks; lane covers block lane/4.
        const uint8_t* b = wr + ((size_t)c * 8 + (lane >> 2)) * 34;
        float d = ld_f16(b);
        uint8_t q[8];
        ld8(b + 2 + 8 * (lane & 3), q);
        #pragma unroll
        for (int t = 0; t < 8; t++)
            v[t] = d * (float)(int8_t)q[t];
    }
    else // QT_IQ2_XXS
    {
        // block_iq2_xxs: half d; uint16 qs[32]. 32-element sub-block ib32 = lane/4 holds two uint32s:
        // aux0 = four 8-bit grid indices, aux1 = four 7-bit sign indices + a 4-bit scale (top bits).
        // Group l = lane%4 is grid row aux0.byte[l] with signs ksigns[(aux1 >> 7l) & 127].
        const uint8_t* b = wr + (size_t)c * 66;
        float d = ld_f16(b);
        int ib32 = lane >> 2, l = lane & 3;
        uint32_t a0 = ld_u32_a2(b + 2 + 8 * ib32);
        uint32_t a1 = ld_u32_a2(b + 2 + 8 * ib32 + 4);
        float db = d * (0.5f + (float)(a1 >> 28)) * 0.25f;
        int gi = (a0 >> (8 * l)) & 0xFF;
        // ksigns_iq2xs[i] = i | (parity(i) << 7): the 8th sign makes the count of negatives even.
        int si = (a1 >> (7 * l)) & 0x7F;
        int signs = si | ((__popc(si) & 1) << 7);
        #pragma unroll
        for (int t = 0; t < 8; t++)
        {
            float g = (float)grid[gi * 8 + t];
            v[t] = db * g * ((signs >> t) & 1 ? -1.0f : 1.0f);
        }
    }
}

