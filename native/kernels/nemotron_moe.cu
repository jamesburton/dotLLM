// acc[t, d] = sum_k w[t*topK + k] * Yslot[(t*topK + k), d], k ascending. grid = (ceil(D / 256), nTok).
extern "C" __global__ void __launch_bounds__(256) moe_weighted_slot_sum_f32(
    const float* __restrict__ Yslot,
    const float* __restrict__ w,
    float* __restrict__ acc,
    const int topK,
    const int D)
{
    const int t = blockIdx.y;
    const int d = blockIdx.x * blockDim.x + threadIdx.x;
    if (d >= D) return;
    float a = 0.0f;
    for (int k = 0; k < topK; k++)
    {
        const int s = t * topK + k;
        a = __fadd_rn(a, __fmul_rn(w[s], Yslot[(size_t)s * D + d]));
    }
    acc[(size_t)t * D + d] = a;
}
